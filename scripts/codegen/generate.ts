/// <reference types="node" />
// Generates the API commands in src/commands/ from api-spec.json.
//
//   pnpm generate:commands [--out <dir>]
//
// The rules are in AGENTS.md, and each file here follows one part:
//
//   spec.ts       what the API has: one `Operation` per endpoint and method
//   commands.ts   which commands exist and what they're called ("Command structure")
//   help.ts       what each command's flags and help say ("Help text")
//   config.ts     the exceptions to those rules
//   types.ts      the command model and the shape of config.ts entries
//   generate.ts   this file: builds the groups, renders one TypeScript file
//                 per group plus index.ts, and formats them with oxfmt
import { execFileSync } from "node:child_process";
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import {
  camel,
  checkUniqueNames,
  commandName,
  lowerFirst,
  newGroup,
  pascal,
  place,
} from "./commands.js";
import * as config from "./config.js";
import {
  applyHelpOverrides,
  buildOptions,
  commandDescription,
} from "./help.js";
import { loadOperations } from "./spec.js";
import type { Command, Group, Operation, Option } from "./types.js";

// ===========================================================================
// Groups
// ===========================================================================

function buildGroups(operations: Operation[]): Group[] {
  const groupNames = new Set(operations.map((op) => op.segments[0]!.name));
  // Groups like `customer-trust` have no endpoints of their own, so they don't
  // own the resources under them in descriptions.
  const groupsWithEndpoints = new Set(
    operations
      .filter((op) => op.segments.length === 1)
      .map((op) => op.segments[0]!.name),
  );
  const groups = new Map<string, Group>();
  for (const op of operations) {
    const placement = place(op);
    const name = placement.groupSegment.name;
    if (!groups.has(name)) groups.set(name, newGroup(name));
    const group = groups.get(name)!;
    const command = commandName(op, placement);
    const queryNames = op.queryParams.map((q) => q.name);
    group.commands.push({
      name: command,
      description: commandDescription(
        command,
        op,
        placement,
        group,
        groupsWithEndpoints.has(name),
      ),
      op,
      options: buildOptions(op, placement, group, groupNames),
      paginated:
        queryNames.includes("pageSize") && queryNames.includes("pageCursor"),
      download: op.returnsFile,
    });
  }
  return [...groups.values()];
}

// ===========================================================================
// Render
// ===========================================================================

// The output is unformatted; oxfmt formats it after it's written.
const generatedHeader =
  "// Code generated by `pnpm generate:commands`. DO NOT EDIT.";

const quote = (s: string) => JSON.stringify(s);
const registerFunction = (g: Group) => `register${pascal(g.name)}Command`;
const groupVariable = (g: Group) => {
  const name = camel(g.name);
  return ["delete", "export", "import", "new"].includes(name)
    ? `${name}Group`
    : name;
};

// Names each generated file imports, collected while rendering.
type Imports = {
  sdk: Set<string>;
  types: Set<string>;
  helpers: Set<string>;
  output: boolean;
};

// `vendors.command("get").description(...).requiredOption(...)`, wrapped in
// `addPaginationOptions` or `addJsonFileOptions` when it takes those flags.
function renderDefinition(
  group: Group,
  command: Command,
  imports: Imports,
): string {
  const chain = [
    `${groupVariable(group)}.command(${quote(command.name)})`,
    `.description(${quote(command.description)})`,
  ];
  for (const o of command.options) {
    const args = [
      quote(`--${o.flag} <${o.placeholder}>`),
      quote(o.description),
    ];
    if (o.repeatable) {
      imports.helpers.add("collectString");
      args.push("collectString", "[] as string[]");
    } else if (o.parseBool) {
      imports.helpers.add("parseOptionalBoolString");
      args.push(`(value) => parseOptionalBoolString(value, ${quote(o.flag)})`);
    }
    chain.push(
      `.${o.required ? "requiredOption" : "option"}(${args.join(", ")})`,
    );
  }
  if (command.download) {
    chain.push(
      `.option("--output <path>", "Write downloaded bytes to file path (default stdout)")`,
    );
  }
  let definition = chain.join("");
  if (command.paginated) {
    imports.helpers.add("addPaginationOptions");
    definition = `addPaginationOptions(${definition})`;
  }
  if (command.op.body === "json") {
    imports.helpers.add("addJsonFileOptions");
    definition = `addJsonFileOptions(${definition})`;
  }
  return definition;
}

// The SDK call for a command, and statements that must run before it.
function renderSdkCall(
  command: Command,
  imports: Imports,
): { before: string[]; call: string } {
  const { op, options } = command;
  const value = (o: Option) =>
    o.target === "file" ? camel(o.flag) : `opts.${camel(o.flag)}`;
  const entry = (o: Option) =>
    o.key === value(o) ? o.key : `${o.key}: ${value(o)}`;
  const entries = (...targets: Option["target"][]) =>
    options.filter((o) => targets.includes(o.target)).map(entry);
  const before: string[] = [];
  const args = ["client: api.client"];

  // Downloads can be any file type; without this the SDK parses text and JSON.
  if (command.download) args.push(`parseAs: "blob"`);

  const path = entries("path");
  if (path.length) args.push(`path: { ${path.join(", ")} }`);

  const query = entries("query");
  if (command.paginated) {
    imports.helpers.add("paginationQuery");
    query.unshift("...paginationQuery(opts)");
  }
  if (query.length === 1 && command.paginated)
    args.push("query: paginationQuery(opts)");
  else if (query.length) args.push(`query: { ${query.join(", ")} }`);

  if (op.body === "json") {
    imports.helpers.add("readJSONPayload");
    imports.types.add(`${op.id}Data`);
    before.push(
      `const body = (await readJSONPayload(opts.json, opts.file)) as ${op.id}Data["body"];`,
    );
    args.push("body");
  } else if (op.body === "multipart") {
    imports.helpers.add("readBinaryFile");
    for (const o of options.filter((o) => o.target === "file")) {
      before.push(
        `const ${camel(o.flag)} = await readBinaryFile(opts.${camel(o.flag)});`,
      );
    }
    args.push(`body: { ${entries("form", "file").join(", ")} }`);
  }

  const fn = lowerFirst(op.id);
  imports.sdk.add(fn);
  return { before, call: `${fn}({ ${args.join(", ")} })` };
}

// The options type for `.action(async (opts: { ... }) => ...)`, or undefined
// when there are no options or `addPaginationOptions` already types them.
function optionsType(command: Command, imports: Imports): string | undefined {
  const { op } = command;
  const field = (o: Option) => {
    const optional = o.required || o.repeatable ? "" : "?";
    let type = o.repeatable ? "string[]" : o.parseBool ? "boolean" : "string";
    if (o.sdkTyped) {
      imports.types.add(`${op.id}Data`);
      type =
        o.target === "path"
          ? `${op.id}Data["path"]["${o.key}"]`
          : `NonNullable<${op.id}Data["query"]>["${o.key}"]`;
      if (o.repeatable) type = `NonNullable<${type}>`;
    }
    return `${camel(o.flag)}${optional}: ${type}`;
  };
  const fields = [
    ...command.options.filter((o) => o.target === "path").map(field),
    ...(command.paginated ? ["pageSize?: number", "pageCursor?: string"] : []),
    ...command.options.filter((o) => o.target !== "path").map(field),
    ...(op.body === "json" ? ["json?: string", "file?: string"] : []),
    ...(command.download ? ["output?: string"] : []),
  ];
  if (fields.every((f) => f.startsWith("page"))) return undefined;
  return `{ ${fields.join("; ")} }`;
}

function renderCommand(
  group: Group,
  command: Command,
  imports: Imports,
): string {
  const sdk = renderSdkCall(command, imports);
  const statements = [...sdk.before];
  if (command.download) {
    imports.helpers.add("withClient");
    imports.helpers.add("writeDownloadedMedia");
    imports.output = true;
    statements.push(`await withClient(getFlags, async (api, flags) => {
      const result = await ${sdk.call};
      if (result.error) throw result.error;
      const dest = opts.output?.trim();
      await writeDownloadedMedia(result.data, dest);
      if (dest) printResponse({ savedTo: dest }, flags);
    });`);
  } else {
    imports.helpers.add("runSdk");
    statements.push(`await runSdk(getFlags, (api) => ${sdk.call});`);
  }
  const body = statements.join("\n");
  const type = optionsType(command, imports);
  const params = !/\bopts\b/.test(body) ? "" : type ? `opts: ${type}` : "opts";
  const definition = renderDefinition(group, command, imports);
  return `${definition}.action(async (${params}) => {\n${body}\n});`;
}

// list, get, create, update, delete first; the rest in spec order.
const commandOrder = ["list", "get", "create", "update", "delete"];
const rank = (c: Command) => {
  const i = commandOrder.indexOf(c.name);
  return i === -1 ? commandOrder.length : i;
};

function renderFile(group: Group): string {
  const imports: Imports = {
    sdk: new Set(),
    types: new Set(),
    helpers: new Set(),
    output: false,
  };
  const commands = [...group.commands]
    .sort((x, y) => rank(x) - rank(y))
    .map((command) => renderCommand(group, command, imports));
  const list = (names: Iterable<string>) => [...names].join(", ");
  const importLines = [
    `import type { Command } from "commander";`,
    imports.sdk.size &&
      `import { ${list(imports.sdk)} } from "../generated/sdk.gen.js";`,
    imports.types.size &&
      `import type { ${list(imports.types)} } from "../generated/types.gen.js";`,
    imports.output && `import { printResponse } from "../output.js";`,
    `import { ${list([...imports.helpers].sort())}, type GetFlags } from "./helpers.js";`,
  ];
  return `${generatedHeader}
${importLines.filter(Boolean).join("\n")}

export function ${registerFunction(group)}(program: Command, getFlags: GetFlags): void {
  const ${groupVariable(group)} = program.command(${quote(group.name)}).description(${quote(group.description)});

  ${commands.join("\n\n")}
}
`;
}

function renderIndex(groups: Group[]): string {
  return `${generatedHeader}
import type { Command } from "commander";
${groups.map((g) => `import { ${registerFunction(g)} } from "./${g.name}.js";`).join("\n")}
import type { GetFlags } from "./helpers.js";

export function registerApiCommands(program: Command, getFlags: GetFlags): void {
  ${groups.map((g) => `${registerFunction(g)}(program, getFlags);`).join("\n")}
}
`;
}

// File contents keyed by file name, with groups in `config.topLevelOrder`.
function renderFiles(groups: Group[]): Map<string, string> {
  const order = (g: Group) => {
    const i = config.topLevelOrder.indexOf(g.name);
    return i === -1 ? config.topLevelOrder.length : i;
  };
  const sorted = [...groups].sort(
    (x, y) => order(x) - order(y) || x.name.localeCompare(y.name),
  );
  const files = new Map(sorted.map((g) => [`${g.name}.ts`, renderFile(g)]));
  files.set("index.ts", renderIndex(sorted));
  return files;
}

// ===========================================================================
// Main
// ===========================================================================

const repoRoot = new URL("../../", import.meta.url).pathname;
const commandsDir = join(repoRoot, "src/commands");
const { values: args } = parseArgs({ options: { out: { type: "string" } } });
const outDir = args.out ?? commandsDir;

const groups = buildGroups(loadOperations(join(repoRoot, "api-spec.json")));
checkUniqueNames(groups);
applyHelpOverrides(groups);

const files = renderFiles(groups);

// Write the files, removing generated files for groups that no longer exist.
mkdirSync(outDir, { recursive: true });
for (const name of readdirSync(outDir)) {
  const path = join(outDir, name);
  if (
    !files.has(name) &&
    name.endsWith(".ts") &&
    readFileSync(path, "utf8").startsWith(generatedHeader)
  ) {
    rmSync(path);
  }
}
const paths = [...files.keys()].map((name) => join(outDir, name));
for (const [name, content] of files) writeFileSync(join(outDir, name), content);
// Pass the config explicitly so `--out` elsewhere gets the same output.
execFileSync(
  join(repoRoot, "node_modules/.bin/oxfmt"),
  ["-c", join(repoRoot, ".oxfmtrc.json"), ...paths],
  { stdio: ["ignore", "ignore", "inherit"] },
);
console.error(`wrote ${files.size} files to ${outDir}`);
