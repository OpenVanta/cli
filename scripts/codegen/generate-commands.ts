// Generates the API commands in src/commands/ from api-spec.json.
//
//   tsx scripts/codegen/generate-commands.ts [--out <dir>]
//
// AGENTS.md ("Command structure") describes the naming rules; ./config.ts holds the
// exceptions and help text overrides. The script runs in stages:
//
//   1. Spec        read each API operation into an `Operation`
//   2. Naming      place it in a group and name it (`vendors list-findings`)
//   3. Options     turn its parameters and body into flags
//   4. Help text   describe the command
//   5. Tree        collect commands into groups, check names, apply overrides
//   6. Render      write one TypeScript file per group, plus index.ts
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as config from "./config.js";

const repoRoot = new URL("../../", import.meta.url).pathname;
const generatedHeader = "// Code generated by scripts/codegen/generate-commands.ts. DO NOT EDIT.";

// ===========================================================================
// 1. Spec
// ===========================================================================

type Schema = {
  $ref?: string;
  type?: string;
  format?: string;
  enum?: string[];
  items?: Schema;
  description?: string;
  properties?: Record<string, Schema>;
  required?: string[];
};

// One API input: a path or query parameter, or a multipart form field.
type Input = {
  name: string;
  required: boolean;
  description: string;
  schema: Schema;
};

// A literal path segment and the ID parameter that follows it, if any:
// `/vendors/{vendorId}` is `{ name: "vendors", param: "vendorId" }`.
type Segment = { name: string; param?: string };

type Operation = {
  id: string;
  method: "get" | "post" | "put" | "patch" | "delete";
  path: string;
  summary: string;
  segments: Segment[];
  pathParams: Input[];
  queryParams: Input[];
  body: "none" | "json" | "multipart";
  formFields: Input[];
  returnsFile: boolean;
};

const spec = JSON.parse(readFileSync(join(repoRoot, "api-spec.json"), "utf8"));

function deref<T>(value: T): T {
  let v = value as { $ref?: string };
  while (v?.$ref) {
    v = v.$ref
      .split("/")
      .slice(1)
      .reduce((acc: any, key) => acc[key], spec);
  }
  return v as T;
}

function toSegments(path: string): Segment[] {
  const segments: Segment[] = [];
  for (const part of path.split("/").filter(Boolean)) {
    const param = /^\{(.+)\}$/.exec(part)?.[1];
    if (param) segments.at(-1)!.param = param;
    else segments.push({ name: part });
  }
  return segments;
}

function loadOperations(): Operation[] {
  const ops: Operation[] = [];
  for (const [path, item] of Object.entries<any>(spec.paths)) {
    for (const method of ["get", "post", "put", "patch", "delete"] as const) {
      const op = item[method];
      if (!op) continue;
      const params = (op.parameters ?? []).map(deref);
      const toInput = (p: any): Input => ({
        name: p.name,
        required: Boolean(p.required),
        description: p.description ?? "",
        schema: deref(p.schema ?? {}),
      });
      const body = op.requestBody ? deref(op.requestBody) : undefined;
      const form = body?.content?.["multipart/form-data"];
      const formSchema: Schema = form ? deref(form.schema) : {};
      const ok = deref(op.responses?.["200"] ?? op.responses?.["201"] ?? {});
      ops.push({
        id: op.operationId,
        method,
        path,
        summary: op.summary ?? "",
        segments: toSegments(path),
        pathParams: params.filter((p: any) => p.in === "path").map(toInput),
        queryParams: params.filter((p: any) => p.in === "query").map(toInput),
        body: form ? "multipart" : body ? "json" : "none",
        formFields: Object.entries(formSchema.properties ?? {}).map(([name, s]) => {
          const schema = deref(s);
          return {
            name,
            required: (formSchema.required ?? []).includes(name),
            description: schema.description ?? "",
            schema,
          };
        }),
        returnsFile: Object.keys(ok.content ?? {}).some((t) => t !== "application/json"),
      });
    }
  }
  return ops;
}

const operations = loadOperations();

