const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const camel = (s: string) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s: string) => camel(s).replace(/^./, (c) => c.toUpperCase());
const lowerFirst = (s: string) => s.replace(/^./, (c) => c.toLowerCase());
const upperFirst = (s: string) => s.replace(/^./, (c) => c.toUpperCase());
const humanize = (s: string) => kebab(s).replace(/-/g, " ");
const article = (s: string) => (/^[aeiou]/i.test(s) && !/^(us|uni|eu)/i.test(s) ? "an" : "a");
const a = (noun: string) => `${article(noun)} ${noun}`;

function singularize(word: string): string {
  if (word === "people") return "person";
  if (word.endsWith("ies")) return `${word.slice(0, -3)}y`;
  if (word.endsWith("sses")) return word.slice(0, -2);
  if (word.endsWith("s") && !/(ss|us)$/.test(word)) return word.slice(0, -1);
  return word;
}

// Singularizes the last word of a kebab-case segment: `security-reviews`.
function singular(segment: string): string {
  const words = segment.split("-");
  words.push(singularize(words.pop()!));
  return words.join("-");
}

const isPlural = (segment: string) => singular(segment) !== segment;

// Display names from `config.nouns`, keyed by "<group> <segment>" or by
// segment, else from the segment itself.
const nounFor = (segment: string, group?: string) =>
  (group && config.nouns[`${group} ${segment}`]) || config.nouns[segment];
const displaySingular = (segment: string, group?: string) =>
  nounFor(segment, group)?.singular ?? humanize(singular(segment));
const displayPlural = (segment: string, group?: string) =>
  nounFor(segment, group)?.plural ?? humanize(segment);

