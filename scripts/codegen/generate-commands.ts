// Groups like `customer-trust` have no endpoints of their own, so they don't
// own the resources under them in descriptions.
const groupsWithEndpoints = new Set(
  operations.filter((op) => op.segments.length === 1).map((op) => op.segments[0]!.name),
);

const prepositions = new Set(["as", "for", "from", "in", "to", "with"]);

// Describes a command from its verb, its subject (the last resource), and the
// subject's owner (the group and any resources in between).
function commandDescription(name: string, op: Operation, p: Placement, group: Group): string {
  const atItem = op.segments.at(-1)!.param !== undefined;
  const verb = upperFirst(name.split("-")[0]!);
  const g = p.group[0];
  const subjectSegment = p.resources.at(-1);
  const parents = p.resources.slice(0, -1);
  const parentSegment = parents.at(-1) ?? p.groupSegment;

  const ownsResources = groupsWithEndpoints.has(p.groupSegment.name) || findMount(op.path);
  const ownerWords = [
    ...(ownsResources ? [group.singular] : []),
    ...parents.map((s) => displaySingular(s.name, g)),
  ];
  const owner = ownerWords.join(" ");
  const owners = parents.length
    ? [...ownerWords.slice(0, -1), displayPlural(parentSegment.name, g)].join(" ")
    : group.plural;
  const subject = subjectSegment && {
    one:
      nounFor(subjectSegment.name, g)?.commandSingular ??
      displaySingular(subjectSegment.name, g),
    many: displayPlural(subjectSegment.name, g),
  };
  // With no owner, the subject stands alone ("List questionnaires").
  const one = subject && owner ? owner : (subject?.one ?? group.singular);
  const many = subject && owner ? owners : (subject?.many ?? group.plural);

  if (p.action) {
    // `add-document-to-control` under `controls` → "document".
    const own = singular(p.groupSegment.name);
    const rest = humanize(p.action.replace(new RegExp(`-(to|from|for)-${own}$`), ""))
      .split(" ")
      .slice(1);
    const target = subject && owner ? `${owner} ${subject.one}` : one;
    // Actions on the collection, e.g. `people offboard`.
    if (!op.segments.some((s) => s.param)) {
      return rest.length === 0 ? `${verb} ${many}` : op.summary;
    }
    if (rest.length === 0) return `${verb} ${a(target)}`;
    if (prepositions.has(rest[0]!)) return `${verb} ${a(target)} ${rest.join(" ")}`;
    // `add-people` → "Add people to a group".
    const object = rest.join(" ");
    const linked = isPlural(rest.at(-1)!) || rest.length > 1 ? object : a(object);
    if (verb === "Add") return `Add ${linked} to ${a(target)}`;
    if (verb === "Remove") return `Remove ${linked} from ${a(target)}`;
    return `${verb} ${object} for ${a(target)}`;
  }

  if (!subject || !owner) {
    switch (verb) {
      case "List":
        return `List ${many}`;
      case "Get":
        return atItem ? `Get ${a(one)} by ID` : `Get ${many}`;
      case "Create":
      case "Upload":
        return `${verb} ${a(one)}`;
      case "Update":
        return atItem ? `Update ${a(one)}` : `Update ${many}`;
      case "Delete":
        return `Delete ${a(one)}`;
      case "Set":
        return `Set ${many}`;
    }
    return op.summary;
  }

  // Under a collection rather than an item: `controls list-deactivated`,
  // `trust-centers add-control-tags`.
  if (parentSegment.param === undefined) {
    if (verb === "Add") return `Add ${subject.many} to ${many}`;
    if (verb === "Remove") return `Remove ${subject.many} from ${many}`;
    if (subjectSegment.name === "order") return `Reorder ${many}`;
    if (verb === "List") {
      // `deactivated-controls` under `controls` → "List deactivated controls".
      const words = humanize(subjectSegment.name)
        .split(" ")
        .filter((w) => w !== p.groupSegment.name && w !== singular(p.groupSegment.name));
      return `List ${words.join(" ")} ${many}`;
    }
    // A resource of its own under the collection: "Create a questionnaire export".
    if (isPlural(subjectSegment.name)) {
      return `${verb} ${a(`${one} ${subject.one}`)}${atItem ? " by ID" : ""}`;
    }
    return `${verb} ${a(`${subject.one} ${one}`)}`;
  }

  if (op.returnsFile) return `Download the ${subject.one} for ${a(one)}`;
  const resource = a(`${one} ${subject.one}`);
  switch (verb) {
    case "List":
      return `List ${subject.many} for ${a(one)}`;
    case "Get":
      return `Get ${resource}${atItem ? " by ID" : ""}`;
    case "Update":
      return !atItem && isPlural(subjectSegment.name)
        ? `Update ${subject.many} for ${a(one)}`
        : `Update ${resource}`;
    case "Create":
    case "Delete":
      return `${verb} ${resource}`;
    case "Add":
      return `Add ${a(subject.one)} to ${a(one)}`;
    case "Remove":
      return `Remove ${a(subject.one)} from ${a(one)}`;
    case "Upload":
      return `Upload ${a(subject.one)} for ${a(one)}`;
    case "Set":
      return subjectSegment.name === "order"
        ? `Reorder ${displayPlural(parentSegment.name, g)} for ${a(ownerWords.slice(0, -1).join(" "))}`
        : `Set ${subject.many} for ${a(one)}`;
  }
  return op.summary;
}

// ===========================================================================
// 5. Tree
// ===========================================================================

type Command = {
  name: string;
  description: string;
  op: Operation;
  options: Option[];
  paginated: boolean;
  download: boolean;
};

type Group = {
  path: string[];
  name: string;
  description: string;
  singular: string;
  plural: string;
  children: Map<string, Group>;
  commands: Command[];
  // Output file name without `.ts`.
  file: string;
};

function newGroup(path: string[], apiSegment: string): Group {
  const noun = config.nouns[path.join(" ")];
  const plural = noun?.plural ?? displayPlural(apiSegment);
  return {
    path,
    name: path.at(-1)!,
    description: `Manage ${plural}`,
    singular: noun?.singular ?? displaySingular(apiSegment),
    plural,
    children: new Map(),
    commands: [],
    // Mounted groups are named after their API path: `vendor-assessment-types`.
    file: path.length === 1 ? path[0]! : apiSegment,
  };
}

// The group for a placement, created on first use.
function groupFor(root: Group, p: Placement): Group {
  let group = root;
  p.group.forEach((name, depth) => {
    const path = p.group.slice(0, depth + 1);
    const apiSegment = depth === p.group.length - 1 ? p.groupSegment.name : name;
    if (!group.children.has(name)) group.children.set(name, newGroup(path, apiSegment));
    group = group.children.get(name)!;
  });
  return group;
}

function buildTree(): Group {
  const root = newGroup([""], "");
  for (const op of operations) {
    const p = place(op);
    const group = groupFor(root, p);
    const name = config.operations[op.id]?.name ?? commandName(op, p);
    const queryNames = op.queryParams.map((q) => q.name);
    group.commands.push({
      name,
      description: commandDescription(name, op, p, group),
      op,
      options: buildOptions(op, p, group),
      paginated: queryNames.includes("pageSize") && queryNames.includes("pageCursor"),
      download: op.returnsFile,
    });
  }
  return root;
}

function* allGroups(group: Group): Generator<Group> {
  for (const child of group.children.values()) {
    yield child;
    yield* allGroups(child);
  }
}

function checkUniqueNames(root: Group): void {
  for (const group of allGroups(root)) {
    const seen = new Map<string, string>();
    for (const { name, op } of group.commands) {
      const path = [...group.path, name].join(" ");
      if (seen.has(name)) {
        throw new Error(
          `duplicate command "${path}" for ${seen.get(name)} and ${op.id}; add a name override in scripts/codegen/config.ts`,
        );
      }
      if (group.children.has(name)) throw new Error(`command "${path}" collides with a group`);
      seen.set(name, op.id);
    }
  }
}

// Replaces generated descriptions with `config.commandHelp` and
// `config.optionHelp`, and fails on entries that match nothing or repeat the
// default, so the overrides stay a list of deliberate wording.
function applyHelpOverrides(root: Group): void {
  const problems: string[] = [];
  const unusedCommands = new Set(Object.keys(config.commandHelp));
  const unusedOptions = new Set(
    Object.entries(config.optionHelp).flatMap(([cmd, flags]) =>
      Object.keys(flags).map((flag) => `${cmd} ${flag}`),
    ),
  );
  const override = (key: string, generated: string, text: string | undefined, unused: Set<string>) => {
    if (text === undefined) return generated;
    unused.delete(key);
    if (text === generated) problems.push(`help text for "${key}" repeats the default`);
    return text;
  };

  for (const group of allGroups(root)) {
    const groupKey = group.path.join(" ");
    group.description = override(groupKey, group.description, config.commandHelp[groupKey], unusedCommands);
    for (const command of group.commands) {
      const key = `${groupKey} ${command.name}`;
      command.description = override(key, command.description, config.commandHelp[key], unusedCommands);
      for (const o of command.options) {
        const flag = `--${o.flag}`;
        o.description = override(`${key} ${flag}`, o.description, config.optionHelp[key]?.[flag], unusedOptions);
      }
    }
  }
  for (const key of unusedCommands) problems.push(`help text for unknown command "${key}"`);
  for (const key of unusedOptions) problems.push(`help text for unknown option "${key}"`);
  if (problems.length) throw new Error(`scripts/codegen/config.ts:\n  ${problems.join("\n  ")}`);
}

