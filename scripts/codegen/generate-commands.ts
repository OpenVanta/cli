const quote = (s: string) => JSON.stringify(s);
const pad = (n: number) => " ".repeat(n);
const indent = (text: string, n: number) =>
  text
    .split("\n")
    .map((line) => (line ? pad(n) + line : line))
    .join("\n");
const sdkFunction = (op: Operation) => lowerFirst(op.id);
const registerFunction = (g: Group) => `register${pascal(g.file)}Command`;
const groupVariable = (g: Group) => {
  const name = camel(g.name);
  return ["delete", "export", "import", "new"].includes(name) ? `${name}Group` : name;
};

// A call on one line when it fits in `width`, else one argument per line.
function call(callee: string, args: string[], width: number): string {
  const inline = `${callee}(${args.join(", ")})`;
  if (inline.length <= width && !inline.includes("\n")) return inline;
  return `${callee}(\n${args.map((arg) => `${indent(arg, 2)},`).join("\n")}\n)`;
}

// An object literal on one line when it fits in `width`, else one entry per line.
function object(entries: string[], width: number): string {
  const inline = `{ ${entries.join(", ")} }`;
  if (inline.length <= width && !inline.includes("\n")) return inline;
  return `{\n${entries.map((e) => `${indent(e, 2)},`).join("\n")}\n}`;
}

// Names each generated file imports, collected while rendering.
type Imports = {
  sdk: Set<string>;
  types: Set<string>;
  helpers: Set<string>;
  output: boolean;
  registers: Map<string, string>;
};

// The SDK call for a command, and statements that must run before it.
function renderSdkCall(command: Command, imports: Imports, width: number) {
  const { op, options } = command;
  const value = (o: Option) => (o.target === "file" ? camel(o.flag) : `opts.${camel(o.flag)}`);
  const entry = (o: Option) => (o.key === value(o) ? o.key : `${o.key}: ${value(o)}`);
  const of = (target: Option["target"][]) => options.filter((o) => target.includes(o.target));
  const before: string[] = [];
  const args = ["client: api.client"];

  const path = of(["path"]).map(entry);
  if (path.length) args.push(`path: ${object(path, width - 8)}`);

  const query = of(["query"]).map(entry);
  if (command.paginated) {
    imports.helpers.add("paginationQuery");
    if (query.length === 0) args.push("query: paginationQuery(opts)");
    else query.unshift("...paginationQuery(opts)");
  }
  if (query.length) args.push(`query: ${object(query, width - 9)}`);

  if (op.body === "json") {
    imports.helpers.add("readJSONPayload");
    imports.types.add(`${op.id}Data`);
    before.push(
      `const body = (await readJSONPayload(\n  opts.json,\n  opts.file,\n)) as ${op.id}Data["body"];`,
    );
    args.push("body");
  } else if (op.body === "multipart") {
    imports.helpers.add("readBinaryFile");
    for (const o of of(["file"])) {
      before.push(`const ${camel(o.flag)} = await readBinaryFile(${`opts.${camel(o.flag)}`});`);
    }
    args.push(`body: ${object(of(["form", "file"]).map(entry), width - 8)}`);
  }

  imports.sdk.add(sdkFunction(op));
  return { before, call: `${sdkFunction(op)}(${object(args, width - sdkFunction(op).length - 2)})` };
}

function renderCommand(group: Group, command: Command, imports: Imports): string {
  // Wrapped in addPaginationOptions/addJsonFileOptions, the chain sits two
  // columns deeper and `.action()` attaches to the wrapper.
  const wrapped = command.paginated || command.op.body === "json";
  const chainIndent = wrapped ? 6 : 4;
  const width = 80 - chainIndent;

  const chain = [
    groupVariable(group),
    `.command(${quote(command.name)})`,
    `.description(${quote(command.description)})`,
  ];
  for (const o of command.options) {
    const args = [quote(`--${o.flag} <${o.placeholder}>`), quote(o.description)];
    if (o.repeatable) {
      imports.helpers.add("collectString");
      args.push("collectString", "[] as string[]");
    } else if (o.parseBool) {
      imports.helpers.add("parseOptionalBoolString");
      args.push(`(value) => parseOptionalBoolString(value, ${quote(o.flag)})`);
    }
    chain.push(call(`.${o.required ? "requiredOption" : "option"}`, args, width));
  }
  if (command.download) {
    const help = "Write downloaded bytes to file path (default stdout)";
    chain.push(call(".option", [quote("--output <path>"), quote(help)], width));
  }
  // Short chains stay on one line: `policies.command("list").description(...)`.
  const inline = chain.join("");
  let head =
    chain.length === 3 && chainIndent - 2 + inline.length < 80
      ? inline
      : [chain[0], ...chain.slice(1).map((line) => indent(line, 2))].join("\n");
  for (const [use, helper] of [
    [command.paginated, "addPaginationOptions"],
    [command.op.body === "json", "addJsonFileOptions"],
  ] as const) {
    if (!use) continue;
    imports.helpers.add(helper);
    head = `${helper}(\n${indent(head, 2)},\n)`;
  }

  const bodyIndent = wrapped ? 4 : 6;
  const sdk = renderSdkCall(command, imports, 80 - bodyIndent - 2);
  const statements = [...sdk.before];
  if (command.download) {
    imports.helpers.add("withClient");
    imports.helpers.add("writeDownloadedMedia");
    imports.output = true;
    statements.push(
      [
        "await withClient(getFlags, async (api, flags) => {",
        indent(`const result = await ${sdk.call};`, 2),
        "  if (result.error) throw result.error;",
        "  const dest = opts.output?.trim();",
        "  await writeDownloadedMedia(result.data, dest);",
        "  if (dest) printResponse({ savedTo: dest }, flags);",
        "});",
      ].join("\n"),
    );
  } else {
    imports.helpers.add("runSdk");
    statements.push(`await runSdk(getFlags, (api) =>\n${indent(sdk.call, 2)},\n);`);
  }
  const body = statements.join("\n");
  const action = renderAction(command, body, wrapped ? 2 : 4, imports);
  const text = wrapped ? `${head}${action};` : `${head}\n${indent(action, 2)};`;
  return indent(text, 2);
}

// `.action(async (opts: { id: string }) => { ... })`, with the options type
// on its own lines when it doesn't fit.
function renderAction(
  command: Command,
  body: string,
  column: number,
  imports: Imports,
): string {
  if (!/\bopts\b/.test(body)) return `.action(async () => {\n${indent(body, 2)}\n})`;
  const fields: string[] = [];
  const add = (o: Option) => {
    const optional = o.required || o.repeatable ? "" : "?";
    let type = o.repeatable ? "string[]" : o.parseBool ? "boolean" : "string";
    if (o.isEnum) {
      imports.types.add(`${command.op.id}Data`);
      type =
        o.target === "path"
          ? `${command.op.id}Data["path"]["${o.key}"]`
          : `NonNullable<${command.op.id}Data["query"]>["${o.key}"]`;
      if (o.repeatable) type = `NonNullable<${type}>`;
    }
    fields.push(`${camel(o.flag)}${optional}: ${type}`);
  };
  command.options.filter((o) => o.target === "path").forEach(add);
  if (command.paginated) fields.push("pageSize?: number", "pageCursor?: string");
  command.options.filter((o) => o.target !== "path").forEach(add);
  if (command.op.body === "json") fields.push("json?: string", "file?: string");
  if (command.download) fields.push("output?: string");
  // Pagination alone doesn't need a type: `addPaginationOptions` provides it.
  if (fields.every((f) => f.startsWith("page"))) {
    return `.action(async (opts) => {\n${indent(body, 2)}\n})`;
  }

  const signature = `async (opts: { ${fields.join("; ")} }) => {`;
  if (column + ".action(".length + signature.length <= 80) {
    return `.action(${signature}\n${indent(body, 2)}\n})`;
  }
  const type = fields.map((field) => `    ${field};`).join("\n");
  return `.action(\n  async (opts: {\n${type}\n  }) => {\n${indent(body, 4)}\n  },\n)`;
}

function renderGroup(group: Group, parent: string, files: Map<string, string>, imports: Imports): string {
  const v = groupVariable(group);
  const declaration = `  const ${v} = ${parent}.command(${quote(group.name)}).description(${quote(group.description)});`;
  const parts = [
    declaration.length <= 80
      ? declaration
      : `  const ${v} = ${parent}\n    .command(${quote(group.name)})\n    .description(${quote(group.description)});`,
  ];
  for (const child of group.children.values()) {
    imports.registers.set(registerFunction(child), child.file);
    parts.push(`  ${registerFunction(child)}(${v}, getFlags);`);
    renderFile(child, files);
  }
  // list, get, create, update, delete first; the rest in spec order.
  const order = ["list", "get", "create", "update", "delete"];
  const rank = (c: Command) => (order.includes(c.name) ? order.indexOf(c.name) : order.length);
  const commands = [...group.commands].sort((x, y) => rank(x) - rank(y));
  for (const command of commands) parts.push(renderCommand(group, command, imports));
  return parts.join("\n\n");
}

// Names in the order given, on one line when they fit.
function renderImport(kind: string, names: Iterable<string>, from: string): string {
  const list = [...names];
  const inline = `${kind} { ${list.join(", ")} } from "${from}";`;
  if (inline.length <= 80) return inline;
  return `${kind} {\n${list.map((n) => `  ${n},`).join("\n")}\n} from "${from}";`;
}

function renderFile(group: Group, files: Map<string, string>): void {
  const imports: Imports = {
    sdk: new Set(),
    types: new Set(),
    helpers: new Set(),
    output: false,
    registers: new Map(),
  };
  const parent = group.path.length === 1 ? "program" : "parent";
  const body = renderGroup(group, parent, files, imports);

  const lines = [generatedHeader, `import type { Command } from "commander";`];
  for (const [fn, file] of imports.registers) {
    lines.push(`import { ${fn} } from "./${file}.js";`);
  }
  if (imports.sdk.size) lines.push(renderImport("import", imports.sdk, "../generated/sdk.gen.js"));
  if (imports.types.size) {
    lines.push(renderImport("import type", imports.types, "../generated/types.gen.js"));
  }
  if (imports.output) lines.push(`import { printResponse } from "../output.js";`);
  // Helpers alphabetically, then the GetFlags type.
  lines.push(renderImport("import", [...[...imports.helpers].sort(), "type GetFlags"], "./helpers.js"));

  files.set(
    `${group.file}.ts`,
    `${lines.join("\n")}\n\nexport function ${registerFunction(group)}(\n  ${parent}: Command,\n  getFlags: GetFlags,\n): void {\n${body}\n}\n`,
  );
}

function renderFiles(root: Group): Map<string, string> {
  const files = new Map<string, string>();
  const order = (g: Group) => {
    const i = config.topLevelOrder.indexOf(g.name);
    return i === -1 ? config.topLevelOrder.length : i;
  };
  const groups = [...root.children.values()].sort(
    (x, y) => order(x) - order(y) || x.name.localeCompare(y.name),
  );
  for (const group of groups) renderFile(group, files);
  files.set(
    "index.ts",
    [
      generatedHeader,
      `import type { Command } from "commander";`,
      ...groups.map((g) => `import { ${registerFunction(g)} } from "./${g.file}.js";`),
      `import type { GetFlags } from "./helpers.js";`,
      "",
      "export function registerApiCommands(program: Command, getFlags: GetFlags): void {",
      ...groups.map((g) => `  ${registerFunction(g)}(program, getFlags);`),
      "}",
      "",
    ].join("\n"),
  );
  return files;
}

// Writes the files, removing generated files for groups that no longer exist.
function writeFiles(files: Map<string, string>, outDir: string): void {
  mkdirSync(outDir, { recursive: true });
  for (const name of readdirSync(outDir)) {
    const path = join(outDir, name);
    if (!files.has(name) && name.endsWith(".ts") && readFileSync(path, "utf8").startsWith(generatedHeader)) {
      rmSync(path);
    }
  }
  for (const [name, content] of files) writeFileSync(join(outDir, name), content);
  console.error(`wrote ${files.size} files to ${outDir}`);
}

