type Option = {
  flag: string;
  placeholder: string;
  description: string;
  required: boolean;
  repeatable: boolean;
  // Parse "true"/"false" into a boolean.
  parseBool: boolean;
  // Takes one of the spec's enum values, typed by the SDK.
  isEnum: boolean;
  // Where the value goes in the SDK call, under `key`.
  target: "path" | "query" | "form" | "file";
  key: string;
};

const topLevelGroups = new Set(
  operations.map((op) => findMount(op.path)?.[0] ?? op.segments[0]!.name),
);

const searchParams = new Set(["q", "search", "searchString"]);
const placeholderWords = new Set([
  "category",
  "direction",
  "group",
  "kind",
  "name",
  "owner",
  "permission",
  "reason",
  "role",
  "scope",
  "severity",
  "slug",
  "source",
  "status",
  "template",
  "title",
  "type",
  "url",
  "visibility",
]);

// The noun a parameter refers to: `statusMatchesAny` → `status`.
function paramNoun(name: string): string {
  const base = name.replace(/(MatchesAny|Filter)$/, "").replace(/Filter$/, "");
  return singularize(kebab(base).split("-").at(-1)!);
}

// See AGENTS.md "Help text" for the placeholder vocabulary.
function placeholderFor(input: Input): string {
  const { name, schema, description } = input;
  const item = schema.type === "array" ? deref(schema.items ?? {}) : schema;
  if (item.type === "boolean" || /^(is|has)[A-Z]/.test(name)) return "bool";
  if (item.format === "date") return "date";
  if (item.format === "date-time" || (!item.enum && /(Date|After|Before)$/.test(name))) {
    return /ISO 8601 date\b/.test(description) ? "date" : "timestamp";
  }
  if (searchParams.has(name)) return "query";
  if (name === "orderBy") return "field";
  if (item.enum) return paramNoun(name);
  if (/\bJSON\b/.test(description)) return "json";
  if (
    /(Id|Ids|Identifier)$/.test(name.replace(/MatchesAny$/, "")) ||
    name === "id" ||
    /\bIDs?\b/.test(description)
  ) {
    return "id";
  }
  if (item.type === "integer" || item.type === "number") return "n";
  const noun = paramNoun(name);
  if (topLevelGroups.has(`${noun}s`)) return "id";
  return placeholderWords.has(noun) ? noun : "text";
}

// First paragraph of a spec description, without "Possible values" lists.
function cleanDescription(text: string): string {
  return text
    .replace(/\s*Possible values:.*$/s, "")
    .split(/\n\s*\n/)[0]!
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\.$/, "");
}

// The spec description, plus enum choices and format hints.
function inputDescription(input: Input, placeholder: string, listed: string): string {
  const { name, schema } = input;
  const item = schema.type === "array" ? deref(schema.items ?? {}) : schema;
  let text = cleanDescription(input.description);
  if (!text && placeholder === "query") text = `Search ${listed}`;
  if (!text) {
    const subject = humanize(name.replace(/MatchesAny$/, ""));
    text = `Filter by ${subject.replace(/\bid(s?)$/, "ID$1")}`;
  }
  text = upperFirst(text)
    // "Boolean determining whether X" → "Whether X".
    .replace(/^Boolean (determining|indicating) w/, "W")
    // `("true" / "false")` → the standard "(true/false)", added below.
    .replace(/\s*\("true" ?\/ ?"false"\)/, "");
  if (placeholder === "timestamp") {
    // "in ISO 8601" and "(ISO 8601 string)" → "ISO 8601 timestamp".
    text = text.replace(/ISO 8601(?: string)?(?! (timestamp|date))/g, "ISO 8601 timestamp");
  }
  if (item.enum && !item.enum.every((v) => text.includes(v))) {
    text += `: ${item.enum.join(", ")}`;
  }
  if (placeholder === "bool" && !text.includes("true/false")) text += " (true/false)";
  if (placeholder === "timestamp" && !text.includes("ISO 8601")) {
    text += " (ISO 8601 timestamp)";
  }
  if (schema.type === "array") text += " (repeatable)";
  return text;
}

// "FAQ ID" for `faqId` when the noun has a configured display name, else the
// humanized parameter name ("Security review ID").
function pathParamDescription(name: string, p: Placement): string {
  const segment = p.resources.find((s) => s.param === name);
  const display =
    segment &&
    (nounFor(segment.name, p.group[0])?.singular ??
      (name === "id" ? displaySingular(segment.name) : undefined));
  if (display) return `${upperFirst(display)} ID`;
  return upperFirst(humanize(name).replace(/ id$/, " ID"));
}

// Whether the SDK types the value as plain `string` (or `string[]`), rather
// than an enum or union.
function isPlainString(schema: Schema): boolean {
  const item = schema.type === "array" ? deref(schema.items ?? {}) : schema;
  return item.type !== "string" ? item.type === "boolean" || item.type === "integer" : !item.enum;
}

function buildOptions(op: Operation, p: Placement, group: Group): Option[] {
  const overrides = config.operations[op.id]?.options ?? {};
  const placeholderOverride = (key: string) =>
    overrides[key]?.placeholder ?? config.params[key]?.placeholder;
  // What a search flag searches: the listed resource, else the group.
  const last = p.resources.at(-1);
  const listed = last ? displayPlural(last.name, p.group[0]) : group.plural;
  const withOverrides = (option: Option, ...extra: (config.OptionOverride | undefined)[]) => {
    for (const o of [...extra, config.params[option.key], overrides[option.key]]) {
      Object.assign(option, Object.fromEntries(Object.entries(o ?? {}).filter(([, v]) => v)));
    }
    return option;
  };
  const options: Option[] = [];

  for (const param of op.pathParams) {
    // The group's own ID is `--id`; `resourceKind` stays `--resource-kind`.
    const own = param.name === p.groupSegment.param && /(^id|Id)$/.test(param.name);
    const option: Option = {
      flag: own ? "id" : kebab(param.name),
      placeholder: own || /Id$/.test(param.name) ? "id" : kebab(param.name),
      description: own
        ? `${upperFirst(group.singular)} ID`
        : pathParamDescription(param.name, p),
      required: true,
      repeatable: false,
      parseBool: false,
      isEnum: !isPlainString(param.schema),
      target: "path",
      key: param.name,
    };
    options.push(withOverrides(option, own ? config.groups[group.path.join(" ")]?.id : undefined));
  }

  for (const param of op.queryParams) {
    if (param.name === "pageSize" || param.name === "pageCursor") continue;
    const placeholder = placeholderOverride(param.name) ?? placeholderFor(param);
    options.push(
      withOverrides({
        flag: kebab(param.name),
        placeholder,
        description: inputDescription(param, placeholder, listed),
        required: param.required,
        repeatable: param.schema.type === "array",
        parseBool: placeholder === "bool" && param.schema.type === "boolean",
        isEnum: !isPlainString(param.schema),
        target: "query",
        key: param.name,
      }),
    );
  }

  for (const field of op.formFields) {
    const isFile = field.schema.format === "binary";
    const placeholder = isFile ? "path" : (placeholderOverride(field.name) ?? placeholderFor(field));
    const fileDescription = cleanDescription(field.description);
    options.push(
      withOverrides({
        flag: kebab(field.name),
        placeholder,
        description: !isFile
          ? inputDescription(field, placeholder, listed)
          : fileDescription
            ? `Path to file to upload: ${lowerFirst(fileDescription)}`
            : field.name === "file"
              ? "Path to file to upload"
              : `Path to ${humanize(field.name)} file to upload`,
        required: field.required,
        repeatable: false,
        parseBool: false,
        isEnum: false,
        target: isFile ? "file" : "form",
        key: field.name,
      }),
    );
  }

  return options;
}

